create or replace function private.is_workshop_member(target_workshop_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.workshop_members wm
    where wm.workshop_id = target_workshop_id
      and wm.user_id = (select auth.uid()) and wm.status = 'active'
  );
$$;

create or replace function private.can_manage_workshop(target_workshop_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.workshop_members wm
    where wm.workshop_id = target_workshop_id
      and wm.user_id = (select auth.uid()) and wm.status = 'active'
      and wm.role in ('owner', 'admin')
  );
$$;

create or replace function private.is_conversation_participant(target_conversation_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.conversations c
    where c.id = target_conversation_id
      and (c.client_id = (select auth.uid()) or private.is_workshop_member(c.workshop_id))
  );
$$;

grant execute on function private.is_workshop_member(uuid) to authenticated;
grant execute on function private.can_manage_workshop(uuid) to authenticated;
grant execute on function private.is_conversation_participant(uuid) to authenticated;

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function private.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (user_id, full_name, email, phone, department, city)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.email, ''),
    coalesce(new.raw_user_meta_data ->> 'phone', ''),
    coalesce(new.raw_user_meta_data ->> 'department', ''),
    coalesce(new.raw_user_meta_data ->> 'city', '')
  ) on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure private.handle_new_user();

do $$
declare table_name text;
begin
  foreach table_name in array array['profiles', 'workshops', 'motorcycles', 'products', 'appointments', 'work_orders']
  loop
    execute format('drop trigger if exists set_%I_updated_at on public.%I', table_name, table_name);
    execute format('create trigger set_%I_updated_at before update on public.%I for each row execute procedure public.set_updated_at()', table_name, table_name);
  end loop;
end $$;

