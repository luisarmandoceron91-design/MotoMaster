revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text not null default '',
  phone text not null default '',
  department text not null default '',
  city text not null default '',
  avatar_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.workshops (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  tagline text not null default '',
  logo_path text,
  accent_color bigint not null default 4294924800,
  status text not null default 'active' check (status in ('active', 'inactive', 'suspended')),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.workshop_members (
  workshop_id uuid not null references public.workshops(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner', 'admin', 'receptionist', 'technician', 'inventory')),
  status text not null default 'active' check (status in ('invited', 'active', 'inactive')),
  created_at timestamptz not null default now(),
  primary key (workshop_id, user_id)
);

create table if not exists public.client_workshops (
  workshop_id uuid not null references public.workshops(id) on delete cascade,
  client_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'active' check (status in ('active', 'blocked', 'archived')),
  joined_at timestamptz not null default now(),
  primary key (workshop_id, client_id)
);

create table if not exists public.motorcycles (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  workshop_id uuid references public.workshops(id) on delete set null,
  plate text,
  brand text not null,
  model text not null,
  model_year integer,
  color text,
  engine_number text,
  vin text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  workshop_id uuid not null references public.workshops(id) on delete cascade,
  sku text,
  name text not null,
  description text not null default '',
  price numeric(14,2) not null default 0 check (price >= 0),
  stock integer not null default 0 check (stock >= 0),
  image_path text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workshop_id, sku)
);

create table if not exists public.appointments (
  id uuid primary key default gen_random_uuid(),
  workshop_id uuid not null references public.workshops(id) on delete cascade,
  client_id uuid not null references auth.users(id) on delete cascade,
  motorcycle_id uuid references public.motorcycles(id) on delete set null,
  scheduled_at timestamptz not null,
  reason text not null default '',
  status text not null default 'requested' check (status in ('requested', 'confirmed', 'in_progress', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.work_orders (
  id uuid primary key default gen_random_uuid(),
  workshop_id uuid not null references public.workshops(id) on delete cascade,
  client_id uuid not null references auth.users(id) on delete cascade,
  motorcycle_id uuid references public.motorcycles(id) on delete set null,
  number bigint generated by default as identity,
  status text not null default 'received' check (status in ('received', 'diagnosis', 'approved', 'in_progress', 'ready', 'delivered', 'cancelled')),
  diagnosis text not null default '',
  notes text not null default '',
  estimated_total numeric(14,2) not null default 0 check (estimated_total >= 0),
  final_total numeric(14,2) not null default 0 check (final_total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workshop_id, number)
);

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  workshop_id uuid not null references public.workshops(id) on delete cascade,
  client_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'open' check (status in ('open', 'closed', 'archived')),
  last_message_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (workshop_id, client_id)
);

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  body text not null default '',
  attachment_path text,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  check (length(trim(body)) > 0 or attachment_path is not null)
);

